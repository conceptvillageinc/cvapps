// ============================================================================
// 住所などの英数字・記号を半角にそろえる（帳票の PDF とプレビューで使う）
//   「久米２丁目９－１１ Ａｂｃ久米ビル ３階」→「久米2丁目9-11 Abc久米ビル 3階」
//   全角の英数字・記号（！〜～）を半角にし、数字の間のハイフンに似た文字（－ − ‐ ー など）を「-」にする。
//   カタカナの長音（ー）は数字の間にあるときだけ「-」にする（「ビール」などは変えない）。
//   全角スペースはそのまま（区切りとして使っているため）。
// ============================================================================

export function toHalfWidth(s) {
  return String(s ?? "")
    .replace(/[！-～]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0xFEE0))
    .replace(/(\d)\s*[ー－−‐‑–—―]\s*(?=\d)/g, "$1-");
}
